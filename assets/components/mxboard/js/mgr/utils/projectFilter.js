import { t } from './i18n.js';

/**
 * Общие пропы поиска для селекторов проекта.
 *
 * Селекторов по интерфейсу шесть (доска, обзор, подзадача, стадии, копирование колонок,
 * очереди), и разъезжаться им нельзя: искать в одном месте по ключу, а в другом только по
 * названию — путаницы больше, чем пользы. Поэтому набор один на всех.
 *
 * `key` в списке полей обязателен: в разговоре, в номерах карточек и в путях репозиториев
 * проект зовут ключом (`mxboard`, `kb-graph`), а официальное название пользователь помнит
 * не всегда.
 *
 * @returns {object} пропы для PrimeVue Select/MultiSelect — оба принимают этот набор
 */
export function projectFilterProps() {
    return {
        filter: true,
        filterFields: ['name', 'key'],
        // Открыл список — и сразу печатаешь: иначе нужен лишний клик по полю поиска.
        autoFilterFocus: true,
        // Запрос не переживает закрытие списка: иначе при следующем открытии список
        // выглядит обрезанным, а причина — фильтр, набранный минуту назад, — на экране
        // уже не видна.
        resetFilterOnHide: true,
        filterPlaceholder: t('mxboard_ui_filter_projects'),
    };
}
